DROP TABLE IF EXISTS tb_pontos_coletas CASCADE;
DROP TABLE IF EXISTS tb_telefones CASCADE;
DROP TABLE IF EXISTS tb_cooperativas CASCADE;
DROP TABLE IF EXISTS tb_condominios CASCADE;
DROP TABLE IF EXISTS tb_lkp_tipos_condominios CASCADE;
DROP TABLE IF EXISTS tb_sindicos CASCADE;
DROP TABLE IF EXISTS tb_usuarios CASCADE;
DROP TABLE IF EXISTS tb_enderecos CASCADE;
DROP TABLE IF EXISTS tb_lkp_tipos_usuarios CASCADE;

CREATE TABLE tb_lkp_tipos_usuarios (
    id_tipo_usuario INTEGER PRIMARY KEY,
    nome_tipo VARCHAR(100) NOT NULL
);

CREATE TABLE tb_enderecos (
    id_endereco INTEGER PRIMARY KEY,
    cep VARCHAR(10) NOT NULL,
    estado CHAR(2) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    complemento VARCHAR(100)
);

CREATE TABLE tb_usuarios (
    id_usuario INTEGER PRIMARY KEY,
    nome_usuario VARCHAR(100) NOT NULL,
    email_usuario VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    data_nascimento DATE,
    cpf VARCHAR(11) UNIQUE,
    url_avatar VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    registro_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_usuario_id INTEGER NOT NULL
        REFERENCES tb_lkp_tipos_usuarios(id_tipo_usuario),
    endereco_id INTEGER NOT NULL
        REFERENCES tb_enderecos(id_endereco)
);

CREATE TABLE tb_sindicos (
    id_sindico INTEGER PRIMARY KEY,
    usuario_id INTEGER UNIQUE NOT NULL
        REFERENCES tb_usuarios(id_usuario)
);

CREATE TABLE tb_lkp_tipos_condominios (
    id_tipo_condominio INTEGER PRIMARY KEY,
    nome_tipo VARCHAR(50) NOT NULL
);

CREATE TABLE tb_condominios (
    id_condominio INTEGER PRIMARY KEY,
    nome_condominio VARCHAR(255) NOT NULL,
    cnpj VARCHAR(18),
    codigo_acesso VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_condominio_id INTEGER REFERENCES tb_lkp_tipos_condominios(id_tipo_condominio),
    url_foto VARCHAR(500),
    sindico_id INTEGER REFERENCES tb_sindicos(id_sindico),
    endereco_id INTEGER UNIQUE REFERENCES tb_enderecos(id_endereco)
);

CREATE TABLE tb_cooperativas (
    id_coop INTEGER PRIMARY KEY,
    cnpj_cooperativa VARCHAR(18) NOT NULL,
    nome_cooperativa VARCHAR(255) NOT NULL,
    email_cooperativa VARCHAR(255) NOT NULL,
    telefone_cooperativa VARCHAR(20),
    usuario_id INTEGER UNIQUE NOT NULL
        REFERENCES tb_usuarios(id_usuario),
    endereco_id INTEGER UNIQUE REFERENCES tb_enderecos(id_endereco)
);

CREATE TABLE tb_telefones (
    id_telefone INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES tb_usuarios(id_usuario),
    numero_contato VARCHAR(20) NOT NULL,
    tipo_telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tb_pontos_coletas (
    id_ponto_coleta INTEGER PRIMARY KEY,
    endereco_id INTEGER REFERENCES tb_enderecos(id_endereco)
);

